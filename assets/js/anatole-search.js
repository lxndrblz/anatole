/*
 * Anatole site search.
 *
 * Searches the JSON index that layouts/partials/search/data.html builds at
 * Hugo build time. No dependencies, no network calls beyond fetching that
 * index once, and no HTML is ever assembled from strings: every result is
 * built from DOM nodes, so index content can never become markup.
 */
(() => {
  'use strict';

  // --- Text normalisation ----------------------------------------------------

  // Arabic letters that have a separate Persian code point for the same
  // glyph, the form U+06C0 takes after decomposition, the tatweel (kashida)
  // stretch character, and two Latin letters that neither lower-casing nor
  // decomposition folds.
  const LETTER_FOLDS = { ي: 'ی', ى: 'ی', ك: 'ک', ة: 'ه', ە: 'ه', ـ: '', ß: 'ss', ı: 'i' };

  const normalize = (value) =>
    String(value)
      .toLowerCase()
      // Compatibility decomposition also folds ligatures, full-width Latin
      // and Arabic presentation forms onto their plain letters.
      .normalize('NFKD')
      // Non-spacing marks (Latin accents, Arabic harakat) and format
      // characters (ZWNJ, ZWJ, soft hyphen): "café" matches "cafe" and
      // "می‌شود" matches "میشود".
      .replace(/[\p{Mn}\p{Cf}]/gu, '')
      .replace(/[يىكةەـßı]/g, (char) => LETTER_FOLDS[char])
      // Persian and Arabic-Indic digits to ASCII: the low nibble of either
      // code point is the digit value.
      .replace(/[۰-۹٠-٩]/g, (digit) => String(digit.charCodeAt(0) & 0x0f));

  // Marks are word characters too: the spacing vowel signs of Indic scripts
  // survive normalisation and sit inside words.
  const WORD_CHAR = /[\p{L}\p{M}\p{N}]/u;
  // Called for every occurrence of every query word, so ASCII, which is most
  // of what it sees, is classified by character code without the regex.
  const isWordChar = (char) => {
    if (char === undefined) return false;
    const code = char.charCodeAt(0);
    if (code < 128) return (code > 47 && code < 58) || (code > 64 && code < 91) || (code > 96 && code < 123);
    return WORD_CHAR.test(char);
  };

  const tokenize = (value) =>
    normalize(value)
      .split(/[^\p{L}\p{M}\p{N}]+/u)
      .filter(Boolean);

  // --- Ranking ---------------------------------------------------------------

  const WHOLE_WORD = 3;
  const WORD_PREFIX = 2;
  const INSIDE_WORD = 1;

  // How well a token matches anywhere in a normalised text. Every occurrence
  // is examined, so a whole-word hit later in the text is not hidden by an
  // earlier hit inside a longer word.
  const matchQuality = (haystack, token) => {
    let best = 0;
    for (let at = haystack.indexOf(token); at !== -1; at = haystack.indexOf(token, at + 1)) {
      const startsWord = !isWordChar(haystack[at - 1]);
      if (startsWord && !isWordChar(haystack[at + token.length])) return WHOLE_WORD;
      best = Math.max(best, startsWord ? WORD_PREFIX : INSIDE_WORD);
    }
    return best;
  };

  // A single letter matches inside almost every word, so on its own it must
  // be a whole word ("c" finds "C" and "C++", not "code"). Scripts written
  // without spaces are exempt: there one character is often a whole word.
  const UNSPACED_SCRIPT =
    /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Thai}\p{Script=Lao}\p{Script=Khmer}\p{Script=Myanmar}]/u;
  const toTerm = (token) => ({
    token,
    minimum: [...token].length === 1 && !UNSPACED_SCRIPT.test(token) ? WHOLE_WORD : INSIDE_WORD,
  });

  // Field weights. A hit in the title outranks a hit anywhere in the body.
  const FIELDS = [
    ['title', 10],
    ['tags', 6],
    ['summary', 3],
    ['text', 1],
  ];

  // Score one document against the query terms. Every term must match in
  // some field (AND semantics), so multi-word queries narrow rather than
  // widen. Each term counts once, through its best field.
  const score = (doc, terms) => {
    let total = 0;
    for (const { token, minimum } of terms) {
      let best = 0;
      for (const [field, weight] of FIELDS) {
        const quality = matchQuality(doc.normalized[field], token);
        if (quality >= minimum) best = Math.max(best, weight * quality);
      }
      if (best === 0) return 0;
      total += best;
    }
    return total;
  };

  // The index is sorted newest-first, and Array.prototype.sort is stable, so
  // equal scores keep that order without a second sort key.
  const rank = (docs, terms, limit) =>
    docs
      .map((doc) => ({ doc, score: score(doc, terms) }))
      .filter((hit) => hit.score > 0)
      .sort((a, b) => b.score - a.score)
      .slice(0, limit)
      .map((hit) => hit.doc);

  // Returns the absolute URL for an index entry, or null unless it is an
  // http(s) page on this site. The index is generated by Hugo, but this keeps
  // a tampered or stale index from producing an off-site or javascript:
  // link. Resolving with the URL parser applies the same whitespace,
  // control-character and backslash handling the browser uses for href, which
  // a pattern match does not; the protocol check is needed because browsers
  // may report the origin "null" for both javascript: URLs and file:// pages.
  const siteHref = (url, location) => {
    if (typeof url !== 'string' || url === '') return null;
    let parsed;
    try {
      parsed = new URL(url, location.href);
    } catch {
      return null;
    }
    const isWeb = parsed.protocol === 'https:' || parsed.protocol === 'http:';
    return isWeb && parsed.origin === location.origin ? parsed.href : null;
  };

  const prepare = (entry) => ({
    title: String(entry.title || ''),
    url: String(entry.url || ''),
    date: String(entry.date || ''),
    section: String(entry.section || ''),
    summary: String(entry.summary || ''),
    text: String(entry.text || ''),
    normalized: {
      title: normalize(entry.title || ''),
      tags: normalize(Array.isArray(entry.tags) ? entry.tags.join(' ') : ''),
      summary: normalize(entry.summary || ''),
      text: normalize(entry.text || ''),
    },
  });

  // --- Snippet ---------------------------------------------------------------

  const SNIPPET_CHARS = 180;
  const SNIPPET_LEAD = 40;
  // How far a cut may move to land on a space instead of inside a word.
  const SNIPPET_SNAP = 20;

  const isLowSurrogate = (code) => code >= 0xdc00 && code <= 0xdfff;
  const isHighSurrogate = (code) => code >= 0xd800 && code <= 0xdbff;

  // Cuts a window of the text around the first match and splits it into
  // pieces, flagging those that contain a term. The window is measured in
  // characters, not words, so it stays short in scripts written without
  // spaces. Only the window is segmented and normalised, never the whole
  // text. `segment` splits a string into word and non-word pieces.
  const snippetParts = (text, normalizedText, terms, segment) => {
    let at = -1;
    for (const { token } of terms) {
      const found = normalizedText.indexOf(token);
      if (found !== -1 && (at === -1 || found < at)) at = found;
    }
    // Normalisation changes the length slightly, so scale the position back
    // onto the original text; the lead-in absorbs the remaining error.
    const estimate = at > 0 ? Math.round((at * text.length) / normalizedText.length) : 0;
    let start = Math.max(0, estimate - SNIPPET_LEAD);
    let end = Math.min(text.length, start + SNIPPET_CHARS);

    if (start > 0) {
      const space = text.indexOf(' ', start);
      if (space !== -1 && space - start < SNIPPET_SNAP) start = space + 1;
      if (isLowSurrogate(text.charCodeAt(start))) start += 1;
    }
    if (end < text.length) {
      const space = text.lastIndexOf(' ', end);
      if (space > start && end - space < SNIPPET_SNAP) end = space;
      if (isHighSurrogate(text.charCodeAt(end - 1))) end -= 1;
    }

    const parts = [];
    for (const piece of segment(text.slice(start, end))) {
      const key = normalize(piece);
      const hit = terms.some(({ token, minimum }) => (minimum === WHOLE_WORD ? key === token : key.includes(token)));
      const last = parts[parts.length - 1];
      if (last && !last.hit && !hit) last.text += piece;
      else parts.push({ text: piece, hit });
    }
    return { parts, clippedStart: start > 0, clippedEnd: end < text.length };
  };

  // Intl objects reject a language tag they cannot parse, and a site may use
  // any string as its language key. Fall back to the browser's own locale.
  const withLocale = (lang, create) => {
    try {
      return create(lang);
    } catch {
      try {
        return create(undefined);
      } catch {
        return null;
      }
    }
  };

  // Word segmentation finds word boundaries in scripts without spaces. Where
  // Intl.Segmenter is missing, splitting on whitespace is the fallback.
  const createSegment = (lang) => {
    const segmenter = withLocale(lang, (locale) => new Intl.Segmenter(locale, { granularity: 'word' }));
    return segmenter
      ? (text) => Array.from(segmenter.segment(text), (part) => part.segment)
      : (text) => text.split(/(\s+)/);
  };

  // --- Dialog ----------------------------------------------------------------

  const init = () => {
    const dialog = document.getElementById('anatoleSearch');
    if (!dialog || typeof dialog.showModal !== 'function') return;

    const root = document.documentElement;
    const input = dialog.querySelector('.searchdialog__input');
    const results = dialog.querySelector('.searchdialog__results');
    const status = dialog.querySelector('.searchdialog__status');
    // The status text sits in a <bdi> so that an untranslated English message
    // keeps its word order inside a right-to-left page.
    const statusText = status.appendChild(document.createElement('bdi'));
    const minLength = Number(dialog.dataset.searchMin) || 2;
    const maxResults = Number(dialog.dataset.searchMax) || 10;
    const slashShortcut = dialog.dataset.searchSlash === 'true';
    const lang = root.lang || undefined;

    const segment = createSegment(lang);
    const numberFormat = withLocale(lang, (locale) => new Intl.NumberFormat(locale));
    const pluralRules = withLocale(lang, (locale) => new Intl.PluralRules(locale));
    // One translated string per sample count; the sample whose plural
    // category equals the real count's category carries the right form.
    const countStrings = JSON.parse(status.dataset.searchCounts);
    const countSamples = Object.keys(countStrings).map(Number);

    let loading = null;
    let ready = false;
    let active = -1;

    const load = () => {
      if (!loading) {
        loading = fetch(dialog.dataset.searchIndex, { credentials: 'same-origin' })
          .then((response) => {
            if (!response.ok) throw new Error(`Search index returned ${response.status}`);
            return response.json();
          })
          .then((entries) => {
            const docs = (Array.isArray(entries) ? entries : []).map(prepare);
            ready = true;
            return docs;
          })
          .catch((error) => {
            loading = null;
            throw error;
          });
      }
      return loading;
    };

    const setStatus = (text, busy = false) => {
      statusText.textContent = text;
      status.hidden = text === '';
      results.setAttribute('aria-busy', busy ? 'true' : 'false');
    };

    const describeCount = (count) => {
      const category = pluralRules.select(count);
      const sample = countSamples.find((n) => pluralRules.select(n) === category);
      const template = countStrings[sample] || countStrings[countSamples[countSamples.length - 1]];
      return template.replace('{n}', numberFormat.format(count));
    };

    const setActive = (index, scroll = true) => {
      const items = results.children;
      active = items.length ? Math.max(-1, Math.min(index, items.length - 1)) : -1;
      const current = results.querySelector('.searchdialog__result--active');
      const target = active >= 0 ? items[active] : null;
      if (!target) input.removeAttribute('aria-activedescendant');
      // Moving the pointer within the result that is already active.
      if (current === target) return;
      if (current) {
        current.classList.remove('searchdialog__result--active');
        current.firstElementChild.setAttribute('aria-selected', 'false');
      }
      if (target) {
        const option = target.firstElementChild;
        target.classList.add('searchdialog__result--active');
        option.setAttribute('aria-selected', 'true');
        if (scroll) target.scrollIntoView({ block: 'nearest' });
        input.setAttribute('aria-activedescendant', option.id);
      }
    };

    const showResults = (items) => {
      results.replaceChildren(...items);
      results.hidden = items.length === 0;
      input.setAttribute('aria-expanded', items.length ? 'true' : 'false');
      setActive(items.length ? 0 : -1);
    };

    const clear = () => {
      showResults([]);
      setStatus('');
    };

    const buildSnippet = (doc, terms) => {
      const useText = doc.text !== '';
      const source = useText ? doc.text : doc.summary;
      if (!source) return null;
      const normalizedSource = useText ? doc.normalized.text : doc.normalized.summary;
      const { parts, clippedStart, clippedEnd } = snippetParts(source, normalizedSource, terms, segment);
      const snippet = document.createElement('p');
      snippet.className = 'searchdialog__result-snippet';
      snippet.dir = 'auto';
      if (clippedStart) snippet.append('… ');
      for (const part of parts) {
        if (part.hit) {
          const mark = document.createElement('mark');
          mark.textContent = part.text;
          snippet.append(mark);
        } else {
          snippet.append(part.text);
        }
      }
      if (clippedEnd) snippet.append(' …');
      return snippet;
    };

    // Each result is a real link, so opening it in a new tab works, and the
    // link itself is the listbox option: an option must not contain another
    // interactive element.
    const buildResult = (doc, index, terms) => {
      const item = document.createElement('li');
      item.className = 'searchdialog__result';
      item.setAttribute('role', 'presentation');

      const link = document.createElement('a');
      link.className = 'searchdialog__result-link';
      link.id = `anatoleSearchResult${index}`;
      link.setAttribute('role', 'option');
      link.setAttribute('aria-selected', 'false');
      link.tabIndex = -1;
      const href = siteHref(doc.url, window.location);
      if (href) link.href = href;

      const title = document.createElement('span');
      title.className = 'searchdialog__result-title';
      title.dir = 'auto';
      title.textContent = doc.title || doc.url;
      link.append(title);

      const meta = [doc.section, doc.date].filter(Boolean).join(' · ');
      if (meta) {
        const metaEl = document.createElement('span');
        metaEl.className = 'searchdialog__result-meta';
        metaEl.textContent = meta;
        link.append(metaEl);
      }

      const snippet = buildSnippet(doc, terms);
      if (snippet) link.append(snippet);

      item.append(link);
      item.addEventListener('pointermove', () => setActive(index, false));
      return item;
    };

    const search = () => {
      const query = input.value.trim();
      if (query.length < minLength) {
        clear();
        return;
      }
      const terms = tokenize(query).map(toTerm);
      if (!terms.length) {
        // Punctuation or emoji only: nothing in the index can match.
        showResults([]);
        setStatus(status.dataset.searchNone);
        return;
      }
      if (!ready) setStatus(status.dataset.searchLoading, true);
      load()
        .then((docs) => {
          // The query may have changed while the index was loading.
          if (input.value.trim() !== query) return;
          const hits = rank(docs, terms, maxResults);
          showResults(hits.map((doc, index) => buildResult(doc, index, terms)));
          setStatus(hits.length ? describeCount(hits.length) : status.dataset.searchNone);
        })
        .catch(() => {
          showResults([]);
          setStatus(status.dataset.searchError);
        });
    };

    // Lock page scrolling while the dialog is open. The scrollbar's width is
    // reserved only if the page had a scrollbar, so nothing shifts sideways
    // either on long pages or on short ones.
    const lockScroll = (locked) => {
      const hadScrollbar = window.innerWidth > root.clientWidth;
      root.classList.toggle('searchdialog-open', locked);
      root.classList.toggle('searchdialog-open--gutter', locked && hadScrollbar);
    };

    const open = () => {
      if (dialog.open) return;
      lockScroll(true);
      dialog.showModal();
      input.focus();
      input.select();
      load().catch(() => {});
    };

    const isEditable = (element) =>
      element instanceof HTMLElement &&
      (element.isContentEditable || /^(input|textarea|select)$/i.test(element.tagName));

    document.querySelectorAll('[data-search-open]').forEach((button) => {
      button.addEventListener('click', open);
      // Warm the index while the pointer travels to the button.
      button.addEventListener('pointerenter', () => load().catch(() => {}), { once: true });
    });

    dialog.querySelectorAll('[data-search-close]').forEach((button) => {
      button.addEventListener('click', () => dialog.close());
    });

    dialog.addEventListener('close', () => lockScroll(false));

    // The form fills the dialog box, so an event whose target is the dialog
    // itself happened on the backdrop. Both the press and the release must
    // land there: dragging a text selection out of the input and letting go
    // over the backdrop must not close the dialog.
    let pressedBackdrop = false;
    dialog.addEventListener('pointerdown', (event) => {
      pressedBackdrop = event.target === dialog;
    });
    dialog.addEventListener('click', (event) => {
      if (pressedBackdrop && event.target === dialog) dialog.close();
    });

    dialog.querySelector('.searchdialog__form').addEventListener('submit', (event) => {
      event.preventDefault();
      const current = results.children[active];
      if (current) current.firstElementChild.click();
    });

    input.addEventListener('input', search);

    input.addEventListener('keydown', (event) => {
      // Keys pressed while an input method is composing belong to it.
      if (event.isComposing) return;
      switch (event.key) {
        // A search input swallows the first Escape to clear itself; close
        // on the first press instead, which is what people expect.
        case 'Escape':
          event.preventDefault();
          dialog.close();
          break;
        case 'ArrowDown':
          event.preventDefault();
          setActive(active + 1);
          break;
        case 'ArrowUp':
          event.preventDefault();
          setActive(active - 1);
          break;
        default:
      }
    });

    // Ctrl/Cmd+K opens the search. "/" does too when the site opts in: a
    // single-key shortcut can be triggered by accident with speech input, so
    // it is off unless params.search.slashShortcut is set.
    document.addEventListener('keydown', (event) => {
      // Autofill and some extensions dispatch keydown events without a key.
      if (dialog.open || typeof event.key !== 'string') return;
      const modifier = event.ctrlKey || event.metaKey;
      const commandK = modifier && !event.altKey && event.key.toLowerCase() === 'k';
      const slash = slashShortcut && event.key === '/' && !modifier && !event.altKey && !isEditable(event.target);
      if (commandK || slash) {
        event.preventDefault();
        open();
      }
    });

    // The button is rendered hidden so that it never shows without a working
    // search; reveal it last, once everything above has been set up.
    document.querySelectorAll('[data-search-control]').forEach((control) => {
      control.hidden = false;
    });
  };

  // Browsers have no `module`; the unit tests in tests/ load this file with one.
  if (typeof module === 'object' && module.exports) {
    module.exports = {
      normalize,
      tokenize,
      matchQuality,
      toTerm,
      rank,
      prepare,
      siteHref,
      snippetParts,
      createSegment,
    };
    return;
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
